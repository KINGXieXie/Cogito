/**
 * 书籍/文学话题识别：用于"她读到相关话题会主动接一句"。
 * 纯关键词匹配，零成本；宁可少触发，也不要因为"图书馆""还活着"这种日常词就插话。
 *
 * 2026-11 调整：去掉"图书馆/活着/推理"这类高频歧义词——
 * 它们让日志里看起来触发了 8 次，实际聊的全是座位、游戏和口头禅。
 */
const KEYWORDS = [
  // 明确的文学/阅读信号
  '小说', '诗', '诗歌', '散文', '文学', '作家', '作者', '书名', '书单', '读书',
  '书店', '读完', '读到', '读完了', '译本', '出版社', '章节', '结局', '文笔', '诗人',
  '散文集', '短篇', '中篇', '长篇', '科幻', '武侠', '名著', '经典小说', '读书笔记',
  // 常见书名 / 作家
  '红楼梦', '三体', '百年孤独', '围城', '平凡的世界', '局外人', '月亮与六便士',
  '小王子', '哈利波特', '沙丘', '罪与罚', '白夜行', '解忧杂货店', '挪威的森林',
  '鲁迅', '张爱玲', '毛姆', '加缪', '余华', '王小波', '村上春树', '陀思妥耶夫斯基',
]

// "说明书/保证书"这类不算文学话题；"活着"只在书名语境下算
const EXCLUDE = /说明书|保证书|通知书|申请书|证书|计划书|企划书|报告书|还活着|活着的传奇/

export function isBookTopic(text) {
  const s = String(text ?? '')
  if (s.length < 2) return false
  if (EXCLUDE.test(s)) return false
  // "活着"单独出现歧义太大：只有配合"余华/小说/书/读"等词才算
  if (s.includes('活着') && !/余华|小说|书|读/.test(s.replace(/活着/g, ''))) return false
  return KEYWORDS.some((kw) => s.includes(kw))
}
