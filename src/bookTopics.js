/**
 * 书籍/文学话题识别：用于"她读到相关话题会主动接一句"。
 * 纯关键词匹配，零成本；宁可少触发，也不要因为一个字"书"就插话。
 */
const KEYWORDS = [
  '小说', '诗', '诗歌', '散文', '文学', '作家', '作者', '书名', '读完', '读到', '读完了',
  '译本', '出版社', '书单', '读书', '图书馆', '书店', '章节', '结局', '主角', '人物',
  '文笔', '诗人', '散文集', '短篇', '中篇', '长篇', '科幻', '推理', '武侠', '悬疑',
  '红楼梦', '三体', '活着', '百年孤独', '围城', '平凡的世界', '局外人', '月亮与六便士',
  '鲁迅', '张爱玲', '毛姆', '加缪', '余华', '王小波', '村上春树', '陀思妥耶夫斯基',
]

// "说明书/保证书"这类不算文学话题
const EXCLUDE = /说明书|保证书|通知书|申请书|证书|计划书|企划书|报告书/

export function isBookTopic(text) {
  const s = String(text ?? '')
  if (s.length < 2) return false
  if (EXCLUDE.test(s)) return false
  let hits = 0
  for (const kw of KEYWORDS) if (s.includes(kw)) hits++
  // 单独一个"书"字太容易误判，只在与其他信号一起时才算
  return hits >= 1
}
